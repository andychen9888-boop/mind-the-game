#!/usr/bin/env node
'use strict';
// Validate every data/cases/*.json and bundle them into app/cases.js (window.MTG_CASES).
// A JS bundle (not fetch) keeps app/index.html working when opened directly from disk.
// Usage: node scripts/build-cases.cjs          -> validate + write
//        node scripts/build-cases.cjs --check  -> validate + fail if app/cases.js is stale
const fs = require('node:fs');
const path = require('node:path');
const { validateCase } = require('./lib/case-schema.cjs');
const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'data/cases');
const ORDER = ['synthetic-counter-01', 'synthetic-buildup-02', 'synthetic-press-03', 'reconstruction-anon-01']; // others follow alphabetically
const files = fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort();
const cases = [];
let failed = false;
for (const f of files) {
  const c = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  const { errors, warnings } = validateCase(c);
  warnings.forEach(w => console.warn(`WARN ${f}: ${w}`));
  if (errors.length) { failed = true; errors.forEach(e => console.error(`FAIL ${f}: ${e}`)); continue; }
  if (path.basename(f, '.json') !== c.caseId) { failed = true; console.error(`FAIL ${f}: file name must equal caseId`); continue; }
  console.log(`ok   ${f}: ${c.dataKind}, ${c.players.length} players, ${c.phases.length} phases, ${c.events.length} events, explanations=${c.generation.explanations}`);
  cases.push(c);
}
if (failed) process.exit(1);
cases.sort((a, b) => {
  const ia = ORDER.indexOf(a.caseId), ib = ORDER.indexOf(b.caseId);
  return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib) || a.caseId.localeCompare(b.caseId);
});
const body = '// GENERATED by scripts/build-cases.cjs from data/cases/*.json. Do not edit by hand.\n'
  + 'window.MTG_CASES = ' + JSON.stringify(cases, null, 1) + ';\n';
const out = path.join(root, 'app/cases.js');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (current !== body) { console.error('FAIL app/cases.js is out of date; run node scripts/build-cases.cjs'); process.exit(1); }
  console.log('ok   app/cases.js is up to date');
} else {
  fs.writeFileSync(out, body);
  console.log(`Wrote app/cases.js (${cases.length} cases)`);
}
