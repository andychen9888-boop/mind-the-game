// Stage 4 — RENDER: assemble ingest + interpret + explain output into a renderer case (mtg-case-1).
// Stage 5 — PERSONALIZE happens in app/index.html: simple vs tactical depth, zh/en, player focus.
// Short on-pitch labels (the shirt number is already on the avatar badge).
const ROLE_TAG = { GK: { zh: '門將', en: 'Keeper' }, RB: { zh: '右後衛', en: 'Right-back' }, LB: { zh: '左後衛', en: 'Left-back' }, CB: { zh: '中後衛', en: 'Centre-back' }, DM: { zh: '防守中場', en: 'Holding mid' }, CM: { zh: '中場', en: 'Midfielder' }, AM: { zh: '前腰', en: 'Playmaker' }, RW: { zh: '右邊鋒', en: 'Right winger' }, LW: { zh: '左邊鋒', en: 'Left winger' }, ST: { zh: '中鋒', en: 'Striker' } };
const r1 = v => Math.round(v * 10) / 10;

// What the About dialog says about the explanation source, based on what actually happened.
function aboutGen(x) {
  const a = x.aiAttempt && x.aiAttempt.status;
  if (x.mode === 'ai-rewritten') return { zh: `本案例的解說由 AI 模型（${x.model}）改寫規則範本草稿而成：結構、事件引用與球員貢獻由程式固定，模型只改寫文字，並通過程式驗證與審查代理。`, en: `The explanations were rewritten by an AI model (${x.model}) from the rule-based draft: structure, event references and contributions are fixed by code, the model only rewrites wording, and the result passed the validator and the reviewer agent.` };
  if (x.mode.startsWith('ai')) return { zh: `本案例的解說由 AI 模型產生（${x.model}），並通過程式驗證與審查代理。`, en: `The explanations in this case were generated by an AI model (${x.model}) and passed the validator and the reviewer agent.` };
  if (a === 'rejected' || a === 'error') return { zh: '曾呼叫 AI 模型，但輸出未通過檢查或呼叫失敗，已捨棄；目前顯示的是離線規則範本。', en: 'An AI model was called, but its output failed the checks or the call failed, so it was discarded. The explanations shown come from offline rule templates.' };
  return { zh: '本案例的解說由離線規則範本產生，沒有呼叫任何 AI 模型。', en: 'The explanations in this case come from offline rule templates. No AI model was called.' };
}

function renderCase(input, interp, explanation, { inputFile = input.sourceFile || `data/synthetic/${input.caseId}.input.json` } = {}) {
  const att = input.match.attackingTeam;
  const snapshots = {};
  const snapAt = (name, t) => { snapshots[name] = interp.frameAt(t).positions; return name; };
  const phases = interp.phases.map((ph, i) => {
    const ex = explanation.phases.find(p => p.id === ph.id);
    const dur = ph.end - ph.start, rel = t => Math.round(Math.min(1, Math.max(0, (t - ph.start) / dur)) * 10000) / 10000;
    const from = 'B' + i, to = 'B' + (i + 1);
    if (!snapshots[from]) snapAt(from, ph.start);
    snapAt(to, ph.end);
    const keyframes = input.frames.filter(f => f.t > ph.start + 0.05 && f.t < ph.end - 0.05).map((f, j) => [rel(f.t), snapAt(`${ph.id}-k${j + 1}`, f.t)]);
    // Ball samples from the event list, normalized to the phase.
    const pts = [[0, ...interp.ballAt(ph.start)]];
    for (const e of ph.ballEvents.filter(e => e.type !== 'press')) for (const [t, p] of [[e.t, e.start], [e.t + e.dur, e.end]]) {
      const q = rel(t);
      if (q > pts[pts.length - 1][0] + 0.001 && q < 0.999) pts.push([q, p[0], p[1]]);
    }
    pts.push([1, ...interp.ballAt(ph.end)]);
    return {
      id: ph.id, start: ph.start, end: ph.end,
      title: ex.title, short: ex.short, sub: ex.sub,
      from, to, keyframes, focus: ph.focus, ball: pts,
      simple: ex.simple, deep: ex.deep, insight: ex.insight, evidence: ex.evidence,
      eventIds: [...ph.ballEvents, ...ph.runs].map(e => e.id),
      evidenceRefs: [...ph.ballEvents.map(e => ({ type: 'event', id: e.id })), { type: 'synthetic-input', file: inputFile }],
      verification: { status: 'synthetic-by-construction', note: { zh: '合成資料：事件與位置由產生器定義，沒有真實畫面可對照。', en: 'Synthetic data: events and positions are defined by the generator; there is no real footage to check against.' } }
    };
  });
  const goal = input.events.find(e => e.type === 'goal');
  const minute = goal ? Math.floor(goal.t / 60) + 1 : null;
  const teams = input.teams, h = teams[input.match.home], a = teams[input.match.away];
  const plain = { zh: t => t.name.zh.replace(/（.*）/, ''), en: t => t.name.en.replace(/ \(.*\)/, '') };
  const scorer = goal ? goal.actor : null;
  const participants = [...new Set(interp.phases.flatMap(p => p.focus))].filter(id => input.players.find(x => x.id === id).team === att);
  return {
    schemaVersion: 'mtg-case-1',
    caseId: input.caseId,
    dataKind: 'synthetic',
    generation: { explanations: explanation.mode, model: explanation.model || undefined, ...(explanation.aiAttempt ? { aiAttempt: explanation.aiAttempt } : {}), segmentation: 'event-rules', positions: 'synthetic', pipeline: 'scripts/pipeline/run.cjs' },
    menuLabel: input.menuLabel || { zh: `合成案例：${input.caseId}`, en: `Synthetic case: ${input.caseId}` },
    match: {
      competition: input.match.competition, date: null, home: input.match.home, away: input.match.away, attackingTeam: att,
      scoreBefore: input.match.scoreBefore, scoreAfter: input.match.scoreAfter, goalTime: goal ? goal.t : null,
      headline: { zh: `${plain.zh(h)} ${input.match.scoreAfter[0]} — ${input.match.scoreAfter[1]} ${plain.zh(a)}`, en: `${plain.en(h).toUpperCase()} ${input.match.scoreAfter[0]} — ${input.match.scoreAfter[1]} ${plain.en(a).toUpperCase()}` },
      subline: { zh: `合成示範賽 · 虛構球隊${minute ? ` · ${minute}′ 反擊進球` : ''}`, en: `SYNTHETIC FIXTURE · FICTIONAL TEAMS${minute ? ` · ${minute}′ COUNTERATTACK` : ''}` },
      scorer, assist: null
    },
    teams,
    attackingDirection: 'ltr',
    coordinates: { range: [0, 100], units: input.coordinates.units, measured: false },
    sources: [
      { label: 'Synthetic input: ' + inputFile, url: null, checked: 'generated by ' + input.generator.script },
      { label: 'Pipeline: scripts/pipeline/run.cjs (ingest → interpret → explain → render)', url: null, checked: 'explanations: ' + explanation.mode }
    ],
    rights: 'Fully synthetic. Fictional teams and players. No footage, crest or likeness.',
    limitations: ['Synthetic data, not a real match', 'Positions sampled every 0.5 s and linearly interpolated', 'Off-camera players are null, not estimated', 'Co-movement of defenders is reported, never causation'],
    ui: {
      chips: participants.slice(0, 5),
      labelWhenRelevant: participants,
      footer: { zh: '合成事件與位置 · 虛構球隊 · 規則分段 · 解說區分觀察與推論', en: 'SYNTHETIC EVENTS & POSITIONS · FICTIONAL TEAMS · RULE-BASED STAGES · OBSERVATION ≠ INTENT' }
    },
    about: {
      zh: [
        '這是合成示範案例：兩支球隊、所有球員、事件與位置都是虛構的，不來自任何真實比賽、轉播或追蹤資料。',
        `資料流程：產生器建立合成事件與每 0.5 秒的位置，並模擬轉播鏡頭只看得到球附近的範圍；流程讀入資料（ingest），依事件規則切出 ${interp.phases.length} 個階段並計算可觀察特徵（interpret），再產生雙語解說（explain），輸出成播放器使用的案例格式（render）。播放器提供白話／戰術兩種深度、中英文與球員聚焦（personalize）。`,
        aboutGen(explanation).zh,
        '鏡頭外的球員位置為未知，不會被補成估計值。防守者與跑動者同時移動時，只描述為同時發生，不宣稱因果。'
      ],
      en: [
        'This is a synthetic demo case: both teams, every player, the events and the positions are fictional and do not come from any real match, broadcast or tracking feed.',
        `Pipeline: a generator creates synthetic events and positions every 0.5 s, with a simulated broadcast camera that only sees the area around the ball. The pipeline ingests the data, segments it into ${interp.phases.length} stages with event rules and computes observable features (interpret), writes bilingual explanations (explain) and outputs the player’s case format (render). The player offers simple/tactical depth, Chinese/English and player focus (personalize).`,
        aboutGen(explanation).en,
        'Players outside the camera view have unknown positions and are never filled in with estimates. When a defender moves with a runner, the replay says the movements happened together and does not claim cause.'
      ]
    },
    players: input.players.map((p, i) => ({ id: p.id, name: p.name, tag: ROLE_TAG[p.role] || undefined, short: p.short, team: p.team, seed: i, identityStatus: 'fictional', role: p.role })),
    snapshots,
    events: input.events.map(({ id, t, type, actor, recipient, start, end, detail }) => ({ id, t, type, actor, ...(recipient ? { recipient } : {}), start, end, ...(detail ? { detail } : {}) })),
    phases,
    summary: explanation.summary
  };
}
module.exports = { renderCase };
